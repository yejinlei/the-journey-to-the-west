print('patched', len(BATCH), 'lines')
for line_idx, text in BATCH:
    src = idx[(1, line_idx)]['text']
    print(f'L{line_idx}: src={len(src)}c -> zh={len(text)}c ratio={len(text)/len(src):.2f}')
