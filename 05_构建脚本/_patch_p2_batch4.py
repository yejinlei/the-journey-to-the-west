print('=== 长度比审计 (src/zh) ===')
for line_idx, zh in BATCH:
    src = idx[(2, line_idx)]['text']
    ratio = len(zh) / len(src)
    flag = 'OK' if 0.90 <= ratio <= 1.15 else '!!'
    print(f'L{line_idx}: src={len(src):4d} zh={len(zh):4d} ratio={ratio:.2f} {flag}')
