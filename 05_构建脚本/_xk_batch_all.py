# 3) 写入
targets = [l for l in lines if l.get('edition') == 'xinke_pingbi']
written_manual = 0
written_from_gb = 0
poem_unmatched = []
for l in targets:
    key = (l['page_no'], l['line_idx'])
    if l.get('text_zh'):
        continue  # 已翻过（title 批1 已完成）
    if l.get('form_type') in ('poem', 'verse') and not l.get('text_zh'):
        # 尝试 gubao 匹配
        gk = l['text'].strip()[:12]
        if gk in gb_map:
            l['text_zh'] = gb_map[gk]
            written_from_gb += 1
            continue
        poem_unmatched.append(key)
    if key in MANUAL:
        l['text_zh'] = MANUAL[key]
        written_manual += 1

