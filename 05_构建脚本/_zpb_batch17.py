for l in data['lines']:
    if l.get('edition') != 'zhu_ping':
        continue
    if l.get('form_type') not in ('main', 'verse'):
        continue
    idx[(l['page_no'], l['line_idx'])] = l

missing = [k for k in BATCH if k not in idx]
assert not missing, f'not found keys: {missing}'

for k, zh in BATCH.items():
    idx[k]['text_zh'] = zh

