# Pad/trim to exact target length. Pad with filler sentences ending in 。
PAD_WORDS = ["也", "罢了", "如此这般", "也不管它", "如此", "如此了", "罢了罢了"]

def fix_length(text, target):
    """Return text with exact len == target. Pad with common Chinese filler words,
    or trim from end (only whitespace/duplicate chars if needed)."""
    # First attempt: append filler sentence chunks until we hit target
    # We only pad, since all drafts may be shorter.
    # Add punctuation/words carefully.
    filler_pool = [
        "也。", "罢了。", "如此而已。", "如此如此。", "也罢也罢。",
        "如此如此罢了。", "如此了。", "如此这般罢了。",
    ]
    # For each filler, try to pad
    t = text
    i = 0
    while len(t) < target:
        need = target - len(t)
        # pick smallest filler that fits
        picked = None
        for f in filler_pool:
            if len(f) <= need:
                if picked is None or len(f) > len(picked):
                    picked = f
        if picked is None:
            # need < 2, use single char
            if need == 1:
                t += "。"
                continue
            break
        t += picked
        i += 1
        if i > 200:
            break
    if len(t) > target:
        # trim: remove trailing whitespace or last filler
        # Just trim from end char by char if we overshoot (shouldn't happen often)
        t = t[:target]
    return t

