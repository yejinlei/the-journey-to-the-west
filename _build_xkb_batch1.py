def parse_merged(path):
    with open(path, "r", encoding="utf-8") as f:
        content = f.read()
    result = {}
    pattern = re.compile(r'## p(\d+)\nLINE_COUNT \d+\nLINE_WIDTHS \[(.*?)\]\n---\n(.*?)\n===', re.DOTALL)
    for m in pattern.finditer(content):
        p = int(m.group(1))
        ws = [int(x) for x in m.group(2).split(',')]
        txt = m.group(3)
        result[p] = (ws, txt)
    return result


def check(data, verbose=True):
    lines_total = 0
    bad = 0
    for x in data:
        lines_total += len(x["widths"])
        s = sum(x["widths"])
        t = len(x["text_zh"])
        d = t - s
        p = 100.0 * d / s
        ok = abs(p) <= 5
        if not ok:
            bad += 1
        if verbose:
            tag = "OK" if ok else ("OVER" if d > 0 else "UNDER")
            print(f'p{x["page"]}: nlines={len(x["widths"])} sum={s} len={t} diff={d:+d} ({p:+.2f}%) {tag}')
    print(f"total_lines: {lines_total}")
    print(f"bad_pages: {bad}")
    return bad


