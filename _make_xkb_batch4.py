def check(label, s, target):
    n = len(s)
    if n == target:
        print(f"  {label}: {n}/{target} EXACT")
        return True
    else:
        print(f"  {label}: {n}/{target} {'OVER' if n>target else 'UNDER'} {n-target}")
        return False

ok_all = True
records = []
for pg in PAGES:
    info = INFO[pg]
    target = info["target"]
    s = TEXTS[pg]
    ok = check(pg, s, target)
    ok_all &= ok
    if ok:
        records.append({"page": int(pg[1:]), "widths": info["widths"], "text_zh": s})
    else:
        records.append({"page": int(pg[1:]), "widths": info["widths"], "text_zh": s, "_STATUS": "MISMATCH"})

