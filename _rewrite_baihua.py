# 上面 REWRITES 里有些是无效的（繁简相同），只保留有效的
def build_effective_rules():
    """只保留左右不同的替换规则。"""
    rules = []
    for src, dst in REWRITES:
        if src != dst:
            rules.append((src, dst))
    # 按源字符串长度降序，长匹配优先
    rules.sort(key=lambda x: -len(x[0]))
    return rules

RULES = build_effective_rules()

