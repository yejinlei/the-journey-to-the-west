# 引号内文保留（对话不改写）：把引号内容暂存，处理后再放回去
def mask_quotes(s):
    """把成对的中文引号内容替换成占位符，返回 (masked_s, dict)。"""
    stores = {}
    def repl(m):
        idx = len(stores)
        stores[idx] = m.group(0)
        return f"\x00{idx}\x00"
    # 中文字符的引号
    masked = re.sub(r"「[^」]*」|『[^』]*』|\u201c[^\u201d]*\u201d", repl, s)
    return masked, stores

def restore_quotes(s, stores):
    for idx, txt in stores.items():
        s = s.replace(f"\x00{idx}\x00", txt)
    return s

def rewrite(text):
    """对一段文言文做白话化。"""
    # 1. 保护引号内容
    masked, stores = mask_quotes(text)
    # 2. 繁→简
    for k, v in TRAD2SIMP.items():
        masked = masked.replace(k, v)
    # 3. 短语替换
    for src, dst in RULES:
        masked = masked.replace(src, dst)
    # 4. 恢复引号
    out = restore_quotes(masked, stores)
    return out

# ============ 应用到 read.json ============

def is_fake(l):
    """判断是否是伪白话行。"""
    txt = l.get("text", "") or ""
    tz = l.get("text_zh", "") or ""
    if not txt or not tz:
        return False
    t_simp = "".join(TRAD2SIMP.get(c, c) for c in txt)
    norm = lambda s: re.sub(r"[\s，。、「」『』：；？！.,:;!?()\[\]\"'\-—…～]+", "", s)
    a = norm(tz)
    b = norm(t_simp)
    if not b:
        return False
    p = min(60, len(a), len(b))
    common = sum(1 for x, y in zip(a[:p], b[:p]) if x == y)
    return (common / max(p, 1)) >= 0.85

