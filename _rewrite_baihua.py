gb_ids = set()
for l in lines:
    if l.get("edition") == "gubao" and is_fake(l):
        gb_ids.add(l["page_id"])
        l["text_zh"] = rewrite(l.get("text", "") or "")

# 更新 char_count
for l in lines:
    if l.get("edition") == "gubao" and l.get("text_zh"):
        l["char_count"] = len(l["text_zh"])

